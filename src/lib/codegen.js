// Robotics Toolbox (Peter Corke) code generation, standard DH only:
// MATLAB for RTB 10 (the toolbox of RVC 2nd ed.) and Python for roboticstoolbox-python (RVC 3rd ed.).
// Generated code is kept ASCII so older MATLAB releases on Windows read the comments correctly.
import { toDeg } from './dh.js';
import { angleExpr, fmtNum } from './format.js';

const len = (x) => fmtNum(x, 6);
const ang = angleExpr;
/** Offset, qlim and q are angles for revolute joints and lengths for prismatic ones. */
const jval = (j, x) => (j.type === 'R' ? ang(x) : len(x));
const hasOffset = (j) => Math.abs(j.offset) > 1e-12;
const padTo = (code, col) => code + ' '.repeat(Math.max(2, col - code.length));
const matStr = (s) => String(s).replace(/'/g, "''");
const pyStr = (s) => String(s).replace(/\\/g, '\\\\').replace(/"/g, '\\"');

export const jointTypes = (joints) => joints.map((j) => j.type).join('');

export function safeIdent(name) {
  return String(name).replace(/[^A-Za-z0-9_]/g, '_').replace(/^[^A-Za-z]+/, '') || 'robot';
}

function wantQlim(j, opts) {
  // Prismatic joints always get qlim: RTB needs it to draw them.
  return j.type === 'P' || opts.qlimRevolute;
}

const title = (robot) =>
  `${robot.name || 'robot'} - ${robot.joints.length}-axis ${jointTypes(robot.joints)} manipulator`;

/* ------------------------------------------------------------------ MATLAB */

export function matlabCode(robot) {
  const { joints, opts } = robot;
  const out = [];
  out.push(`%% ${title(robot)}`);
  out.push('% Robotics Toolbox for MATLAB (RTB 10, as used in RVC 2nd ed.) - generated by DH Parameters');
  out.push('% Standard DH:  A_j = Rz(theta_j) * Tz(d_j) * Tx(a_j) * Rx(alpha_j)');
  out.push('% Lengths in metres, angles in radians.');
  out.push('');
  out.push('clear L');

  if (opts.matlabStyle === 'matrix') {
    // Classic RVC form: Link([theta d a alpha sigma offset])
    const heads = ['theta', 'd', 'a', 'alpha', 'sigma', 'offset'];
    const rows = joints.map((j) => [
      j.type === 'P' ? ang(j.theta) : '0',
      j.type === 'R' ? len(j.d) : '0',
      len(j.a),
      ang(j.alpha),
      j.type === 'R' ? '0' : '1',
      jval(j, j.offset),
    ]);
    const w = heads.map((h, c) => Math.max(h.length, ...rows.map((r) => r[c].length)));
    const cells = (r) => r.map((x, c) => (c < r.length - 1 ? x.padEnd(w[c]) : x)).join('  ');
    const prefix = `L(${joints.length}) = Link([`;
    out.push('%' + ' '.repeat(prefix.length - 1) + cells(heads));
    rows.forEach((r, i) => {
      const lead = `L(${i + 1}) = Link([`.padEnd(prefix.length);
      out.push(`${lead}${cells(r)}]);`);
    });
    joints.forEach((j, i) => {
      if (wantQlim(j, opts)) out.push(`L(${i + 1}).qlim = [${jval(j, j.qlim[0])} ${jval(j, j.qlim[1])}];`);
    });
  } else {
    joints.forEach((j, i) => {
      const args = j.type === 'R' ? [`'d', ${len(j.d)}`] : [`'theta', ${ang(j.theta)}`];
      args.push(`'a', ${len(j.a)}`, `'alpha', ${ang(j.alpha)}`);
      if (hasOffset(j)) args.push(`'offset', ${jval(j, j.offset)}`);
      if (wantQlim(j, opts)) args.push(`'qlim', [${jval(j, j.qlim[0])} ${jval(j, j.qlim[1])}]`);
      out.push(`L(${i + 1}) = ${j.type === 'R' ? 'Revolute' : 'Prismatic'}(${args.join(', ')});`);
    });
  }

  out.push('');
  out.push(`robot = SerialLink(L, 'name', '${matStr(robot.name || 'robot')}');`);

  if (opts.demo) {
    const q = joints.map((j) => jval(j, j.q)).join(' ');
    out.push('');
    out.push('% --- try it ---');
    out.push(padTo(`q = [${q}];`, 30) + '% joint coordinates');
    out.push(padTo('robot', 30) + '% show the DH table');
    out.push(padTo('T = robot.fkine(q)', 30) + '% end-effector pose');
    out.push(padTo('robot.plot(q)', 30) + '% 3D stick figure');
    out.push(padTo('% robot.teach(q)', 30) + '% ...or drive it with sliders');
  }
  return out.join('\n');
}

/* ------------------------------------------------------------------ Python */

export function pythonCode(robot) {
  const { joints, opts } = robot;
  const out = [];
  out.push(`# ${title(robot)}`);
  out.push('# Robotics Toolbox for Python (as used in RVC 3rd ed.) - generated by DH Parameters');
  out.push('# Standard DH:  A_j = Rz(theta_j) Tz(d_j) Tx(a_j) Rx(alpha_j)');
  out.push('# Lengths in metres, angles in radians.');
  out.push('');
  out.push('from math import pi');
  out.push('import roboticstoolbox as rtb');
  out.push('');
  out.push('robot = rtb.DHRobot(');
  out.push('    [');
  joints.forEach((j) => {
    const cls = j.type === 'R' ? 'RevoluteDH' : 'PrismaticDH';
    const args = j.type === 'R' ? [`d=${len(j.d)}`] : [`theta=${ang(j.theta)}`];
    args.push(`a=${len(j.a)}`, `alpha=${ang(j.alpha)}`);
    if (hasOffset(j)) args.push(`offset=${jval(j, j.offset)}`);
    if (wantQlim(j, opts)) args.push(`qlim=[${jval(j, j.qlim[0])}, ${jval(j, j.qlim[1])}]`);
    out.push(`        rtb.${cls}(${args.join(', ')}),`);
  });
  out.push('    ],');
  out.push(`    name="${pyStr(robot.name || 'robot')}",`);
  out.push(')');
  out.push('');
  out.push(padTo('print(robot)', 30) + '# show the DH table');

  if (opts.demo) {
    const q = joints.map((j) => jval(j, j.q)).join(', ');
    out.push('');
    out.push('# --- try it ---');
    out.push(padTo(`q = [${q}]`, 30) + '# joint coordinates');
    out.push(padTo('T = robot.fkine(q)', 30) + '# end-effector pose (SE3)');
    out.push('print(T)');
    out.push(padTo('robot.plot(q, block=True)', 30) + '# 3D stick figure');
    out.push(padTo('# robot.teach(q)', 30) + '# ...or drive it with sliders');
  }
  return out.join('\n');
}

/* ------------------------------------------------------- DH table and ETS */

function symbols(robot) {
  const deg = robot.units === 'deg';
  const A = (x) => (deg ? `${fmtNum(toDeg(x), 2)}°` : fmtNum(x, 4));
  const L = (x) => fmtNum(x, 5);
  const qv = (j, i) => {
    if (!hasOffset(j)) return `q${i + 1}`;
    const mag = j.type === 'R' ? A(Math.abs(j.offset)) : L(Math.abs(j.offset));
    return `q${i + 1} ${j.offset < 0 ? '-' : '+'} ${mag}`;
  };
  return { A, L, qv };
}

/** The DH table as the Robotics Toolbox prints it (variables shown as q1, q2...). */
export function dhTableText(robot) {
  const { joints } = robot;
  const { A, L, qv } = symbols(robot);
  const rows = joints.map((j, i) => {
    const theta = j.type === 'R' ? qv(j, i) : A(j.theta);
    const d = j.type === 'P' ? qv(j, i) : L(j.d);
    return [String(i + 1), theta, d, L(j.a), A(j.alpha)];
  });
  const cols = ['j', 'theta', 'd', 'a', 'alpha'];
  const w = cols.map((h, c) => Math.max(h.length, ...rows.map((r) => r[c].length)) + 2);
  const sep = '+' + w.map((x) => '-'.repeat(x)).join('+') + '+';
  const line = (cells) =>
    '|' + cells.map((s, c) => (c === 0 ? ` ${s.padEnd(w[c] - 1)}` : `${s.padStart(w[c] - 1)} `)).join('|') + '|';
  const head = `${robot.name || 'robot'}:: ${joints.length} axis, ${jointTypes(joints)}, stdDH`;
  return [head, sep, line(cols), sep, ...rows.map(line), sep].join('\n');
}

/** Elementary transform sequence, zero terms dropped: Rz(q1) · Tz(0.4) · Rx(90°) · ... */
export function etsString(robot) {
  const { A, L, qv } = symbols(robot);
  const nz = (x) => Math.abs(x) > 1e-12;
  const parts = [];
  robot.joints.forEach((j, i) => {
    const rz = j.type === 'R' ? `Rz(${qv(j, i)})` : nz(j.theta) ? `Rz(${A(j.theta)})` : null;
    const tz = j.type === 'P' ? `Tz(${qv(j, i)})` : nz(j.d) ? `Tz(${L(j.d)})` : null;
    const tx = nz(j.a) ? `Tx(${L(j.a)})` : null;
    const rx = nz(j.alpha) ? `Rx(${A(j.alpha)})` : null;
    parts.push(...[rz, tz, tx, rx].filter(Boolean));
  });
  return parts.join(' · ');
}

/* ------------------------------------------------- one link (Learn tab) */

export function singleLinkCode(p, lang) {
  const R = p.type === 'R';
  const q = R ? ang(p.theta) : len(p.d);
  const qNote = R ? `${fmtNum(toDeg(p.theta), 1)} deg` : `${len(p.d)} m`;
  if (lang === 'matlab') {
    const first = R ? `'d', ${len(p.d)}` : `'theta', ${ang(p.theta)}`;
    return [
      `L = ${R ? 'Revolute' : 'Prismatic'}(${first}, ...`,
      `      'a', ${len(p.a)}, 'alpha', ${ang(p.alpha)});`,
      padTo(`A = L.A(${q})`, 22) + `% q = ${qNote}`,
    ].join('\n');
  }
  const first = R ? `d=${len(p.d)}` : `theta=${ang(p.theta)}`;
  return [
    'from math import pi',
    'import roboticstoolbox as rtb',
    '',
    `L = rtb.${R ? 'RevoluteDH' : 'PrismaticDH'}(${first}, a=${len(p.a)}, alpha=${ang(p.alpha)})`,
    padTo(`A = L.A(${q})`, 22) + `# SE3, q = ${qNote}`,
  ].join('\n');
}
